<?php
/**
 * Export credit. This is intentionally not exposed in settings.
 *
 * A short, invisible source-code credit is added to every exported file.
 * It never renders in the browser. There is no option to disable it.
 *
 * @package WP_Static_Export
 */

defined( 'ABSPATH' ) || exit;

/**
 * Class WSE_Brand
 */
class WSE_Brand {

	/**
	 * Author name.
	 *
	 * @var string
	 */
	const AUTHOR = 'Abdul Aouwal';

	/**
	 * Author website.
	 *
	 * @var string
	 */
	const SITE = 'https://abdulaouwal.com';

	/**
	 * Plugin repository.
	 *
	 * @var string
	 */
	const REPO = 'https://github.com/aouwalitshikkha/wp-static-export';

	/**
	 * Whether the export credit should be included.
	 *
	 * Forced on when the WSE_FORCE_CREDIT constant is defined and true
	 * (GitHub distribution). Otherwise it follows the opt-in "show_credit"
	 * setting, which defaults to off.
	 *
	 * @return bool
	 */
	public static function should_include() {
		if ( defined( 'WSE_FORCE_CREDIT' ) && WSE_FORCE_CREDIT ) {
			return true;
		}
		return (bool) WSE_Settings::get( 'show_credit', 0 );
	}

	/**
	 * Credit lines used in exported source comments.
	 *
	 * @return string[]
	 */
	public static function lines() {
		return array(
			'Static site generated by WP Static Export (' . self::REPO . ')',
			'Crafted by ' . self::AUTHOR . ' - Technical SEO Consultant (' . self::SITE . ')',
		);
	}

	/**
	 * HTML comment credit for exported pages. Invisible in the browser.
	 *
	 * @return string Full "<!-- ... -->" block.
	 */
	public static function html_comment() {
		return '<!--' . "\n" . '  ' . implode( "\n" . '  ', self::lines() ) . "\n" . '-->';
	}

	/**
	 * XML comment credit for feeds and sitemap.xml.
	 *
	 * @return string Full "<!-- ... -->" block.
	 */
	public static function xml_comment() {
		return '<!-- ' . implode( ' | ', self::lines() ) . ' -->';
	}

	/**
	 * Plain-text credit for robots.txt, _redirects and _headers.
	 *
	 * @return string
	 */
	public static function text_comment() {
		return '# ' . implode( ' | ', self::lines() );
	}

	/**
	 * Per-export fingerprint lines (unique to each export job).
	 *
	 * @param string $job_id Export job ID.
	 * @return string[]
	 */
	public static function footer_lines( $job_id ) {
		$lines   = self::lines();
		$lines[] = 'Export: ' . substr( (string) $job_id, 0, 12 ) . ' / ' . gmdate( 'Y-m-d H:i' ) . ' UTC';
		return $lines;
	}

	/**
	 * Footer HTML comment credit with per-export fingerprint.
	 *
	 * @param string $job_id Export job ID.
	 * @return string Full "<!-- ... -->" block.
	 */
	public static function html_footer_comment( $job_id ) {
		return '<!--' . "\n" . '  ' . implode( "\n" . '  ', self::footer_lines( $job_id ) ) . "\n" . '-->';
	}

	/**
	 * Encoded credit marker. Decodes (base64) to the plain credit text.
	 * A plain-text search for the author name or URL will not find it.
	 *
	 * @return string Full "<!-- ... -->" block, safe in HTML and XML.
	 */
	public static function encoded_comment() {
		return '<!--' . base64_encode( implode( ' | ', self::lines() ) ) . '-->';
	}

	/**
	 * CSS file credit.
	 *
	 * @return string
	 */
	public static function css_comment() {
		return '/* ' . implode( ' | ', self::lines() ) . ' */';
	}

	/**
	 * JS file credit.
	 *
	 * @return string
	 */
	public static function js_comment() {
		return '// ' . implode( ' | ', self::lines() );
	}
}
